/**
 * Compile RetainerRelease.sol with solc-js (no system solc/forge required).
 *
 * Local sources are provided directly, keyed by their resolved source-unit
 * names so relative imports resolve among them; the import callback resolves
 * `@openzeppelin/...` from node_modules. Emits output/RetainerRelease.{abi,bin}
 * and a typed abi/RetainerRelease.ts.
 */
import { createRequire } from "module";
import * as fs from "fs";
import { join } from "path";

const require = createRequire(import.meta.url);
// eslint-disable-next-line @typescript-eslint/no-var-requires
const solc = require("solc");

const ROOT = process.cwd();
const read = (p: string) => fs.readFileSync(p, "utf8");

const sources: Record<string, { content: string }> = {
  "src/RetainerRelease.sol": { content: read(join(ROOT, "src", "RetainerRelease.sol")) },
  "interfaces/ReceiverTemplate.sol": { content: read(join(ROOT, "interfaces", "ReceiverTemplate.sol")) },
  "interfaces/IReceiver.sol": { content: read(join(ROOT, "interfaces", "IReceiver.sol")) },
  "interfaces/IERC165.sol": { content: read(join(ROOT, "interfaces", "IERC165.sol")) },
};

function findImports(importPath: string): { contents: string } | { error: string } {
  try {
    const base = importPath.startsWith("@") ? join(ROOT, "node_modules", importPath) : join(ROOT, importPath);
    return { contents: read(base) };
  } catch {
    return { error: `Import not found: ${importPath}` };
  }
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));

const diagnostics: Array<{ severity: string; formattedMessage: string }> = output.errors ?? [];
const errors = diagnostics.filter((e) => e.severity === "error");
for (const w of diagnostics.filter((e) => e.severity !== "error")) console.warn(w.formattedMessage);
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

const contract = output.contracts["src/RetainerRelease.sol"]["RetainerRelease"];
const abi = contract.abi;
const bytecode: string = contract.evm.bytecode.object;

fs.mkdirSync(join(ROOT, "output"), { recursive: true });
fs.writeFileSync(join(ROOT, "output", "RetainerRelease.abi"), JSON.stringify(abi, null, 2));
fs.writeFileSync(join(ROOT, "output", "RetainerRelease.bin"), bytecode);
fs.mkdirSync(join(ROOT, "abi"), { recursive: true });
fs.writeFileSync(
  join(ROOT, "abi", "RetainerRelease.ts"),
  `// Generated by compile.ts — do not edit.\nexport const RetainerReleaseAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);

console.log(
  `Compiled RetainerRelease: ${abi.length} ABI entries, ${Math.round(bytecode.length / 2)} bytes of bytecode.`,
);
