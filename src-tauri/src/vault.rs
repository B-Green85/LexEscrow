/// DocuSign JWT-Grant credentials (spec §18 / §24).
///
/// `jwt_private_key` is the most sensitive value the vault holds — an RSA PEM
/// that can mint access tokens impersonating the account user. `Zeroize` +
/// `ZeroizeOnDrop` wipe every field from memory when the struct is dropped, so a
/// resolved copy handed to `docusign.rs` leaves nothing behind after the request
/// completes. Like every other entry, it never crosses IPC — only
/// `DocuSignPublic` does.
#[derive(Debug, Clone, Default, Serialize, Deserialize, Zeroize, ZeroizeOnDrop)]
#[serde(rename_all = "camelCase")]
pub struct DocuSignSecret {
    pub integration_key: String,
    pub user_id: String,
    pub account_id: String,
    pub base_uri: String, // https://demo.docusign.net for sandbox
    pub jwt_private_key: String, // RSA PEM — most sensitive field
    pub environment: String, // "sandbox" | "production"
}

/// AnchorReceipt seal key (spec §8) — 32 random bytes, base64.
///
/// Unlike every other entry in the vault this is **not** a user-supplied
/// credential: it is generated by LexEscrow on first unlock and never
/// displayed, edited, or deleted through the UI. It lives here because it is
/// the one secret that must be per-install and must survive restarts — the
/// registry claim in spec §8 is provenance *across time*, so a seal issued
/// last month has to remain reproducible today.
#[derive(Debug, Clone, Default, Serialize, Deserialize, Zeroize, ZeroizeOnDrop)]
#[serde(rename_all = "camelCase")]
pub struct SealEntry {
    pub key_b64: String,
}

/// Clio practice-management webhook config (spec §14 V1).
///
/// The URL is not a secret, but the API key is a bearer token for a firm's
/// matter data — so the whole entry gets the same `Zeroize` treatment as the
/// DocuSign credential rather than being split across a secret and a plain
